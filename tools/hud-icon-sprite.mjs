// HUD icon sprite: packs every painted HUD icon (apps/client/brand/hud-icons/<name>.webp,
// transparent 128 px) into one sheet, apps/client/public/ui/icons.webp, so the game loads one image
// instead of one request per icon. Also writes apps/client/src/hud/iconSprite.ts with each icon's
// cell, which GameIcon turns into a CSS background position.
// Each cell is the 128 px icon plus a 2 px transparent gutter on every side, so scaled-down icons
// never pick up a neighbour's edge. The sheet URL carries a content hash for cache busting.
//
// Usage: node tools/hud-icon-sprite.mjs   (run again after adding or changing an icon)
import { createHash } from "node:crypto";
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "apps", "client", "brand", "hud-icons");
const OUT = join(ROOT, "apps", "client", "public", "ui", "icons.webp");
const MAP = join(ROOT, "apps", "client", "src", "hud", "iconSprite.ts");

export const ICON = 128;
export const GUTTER = 2;
export const CELL = ICON + GUTTER * 2;
export const COLUMNS = 6;

async function main() {
  const names = readdirSync(SRC)
    .filter((f) => f.endsWith(".webp"))
    .map((f) => f.slice(0, -5))
    .sort();
  const rows = Math.ceil(names.length / COLUMNS);
  const tiles = await Promise.all(
    names.map(async (name, i) => ({
      input: await sharp(join(SRC, `${name}.webp`))
        .resize(ICON, ICON, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
        .toBuffer(),
      left: (i % COLUMNS) * CELL + GUTTER,
      top: Math.floor(i / COLUMNS) * CELL + GUTTER,
    })),
  );
  const sheet = await sharp({
    create: {
      width: COLUMNS * CELL,
      height: rows * CELL,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite(tiles)
    .webp({ quality: 90, alphaQuality: 100, effort: 6 })
    .toBuffer();
  writeFileSync(OUT, sheet);
  const hash = createHash("sha256").update(sheet).digest("hex").slice(0, 8);

  const cells = names.map((n, i) => `  "${n}": [${i % COLUMNS}, ${Math.floor(i / COLUMNS)}],`);
  writeFileSync(
    MAP,
    `// Generated by tools/hud-icon-sprite.mjs from apps/client/brand/hud-icons. Do not edit.
// Cell [column, row] of each HUD icon in the sprite sheet public/ui/icons.webp.

export const ICON_SPRITE = {
  /** Sheet path under the app base, with a content hash so browsers drop a stale sheet. */
  path: "ui/icons.webp?v=${hash}",
  columns: ${COLUMNS},
  rows: ${rows},
} as const;

export const ICON_CELLS = {
${cells.join("\n")}
} as const satisfies Record<string, readonly [number, number]>;

export type GameIconName = keyof typeof ICON_CELLS;
`,
  );
  console.log(
    `wrote ${OUT} (${names.length} icons, ${COLUMNS}x${rows}, ${sheet.length} bytes) and ${MAP}`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
